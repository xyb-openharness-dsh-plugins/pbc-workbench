-- 0004：化验项自带实验室名称。
--
-- 为什么：`lab_panels` 上已经有 `lab_name`（一次抽血 / 一张单子的来源），
-- 但一张"化验汇总单"里可能同时抄了本院与外院的结果（演示数据里就有一条：
-- 2026-09 那张的 ALP 来自"外院报告（未印上限）"，其余指标来自市一院）。
-- 只留面板级 lab_name 时，读模型会把外院那条也标成市一院 —— 参考区间明明不同，
-- 来源却写成一个，用户核对时会以为是自己记错了。
--
-- 列可空：为空时读模型回落到 `lab_panels.lab_name`，不改变既有数据的行为。

ALTER TABLE lab_items ADD COLUMN lab_name TEXT;
